DROP DATABASE IF EXISTS pbkk_siakad;
CREATE DATABASE pbkk_siakad CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE pbkk_siakad;

CREATE TABLE dosen (
    id     INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nidn   CHAR(10)     NOT NULL UNIQUE,
    nama   VARCHAR(100) NOT NULL,
    email  VARCHAR(100) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE mahasiswa (
    id        INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nim       CHAR(10)     NOT NULL UNIQUE,
    nama      VARCHAR(100) NOT NULL,
    gender    ENUM('L','P') NOT NULL,
    prodi     VARCHAR(60)  NOT NULL DEFAULT 'Teknik Informatika',
    angkatan  YEAR         NOT NULL,
    email     VARCHAR(100) NOT NULL UNIQUE
) ENGINE=InnoDB;

-- Akun login. Satu akun terhubung ke dosen ATAU mahasiswa (admin tidak keduanya).
CREATE TABLE users (
    id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    username      VARCHAR(30)  NOT NULL UNIQUE,
    password      VARCHAR(255) NOT NULL,
    role          ENUM('admin','dosen','mahasiswa') NOT NULL,
    nama          VARCHAR(100) NOT NULL,
    dosen_id      INT UNSIGNED NULL,
    mahasiswa_id  INT UNSIGNED NULL,
    last_login    DATETIME     NULL,
    CONSTRAINT fk_users_dosen     FOREIGN KEY (dosen_id)     REFERENCES dosen(id)     ON DELETE CASCADE,
    CONSTRAINT fk_users_mahasiswa FOREIGN KEY (mahasiswa_id) REFERENCES mahasiswa(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE matakuliah (
    id        INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    kode      CHAR(6)      NOT NULL UNIQUE,
    nama      VARCHAR(100) NOT NULL,
    sks       TINYINT UNSIGNED NOT NULL,
    semester  TINYINT UNSIGNED NOT NULL
) ENGINE=InnoDB;

-- Kelas = mata kuliah yang dibuka pada satu tahun ajaran, lengkap dengan jadwalnya
CREATE TABLE kelas (
    id             INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    matakuliah_id  INT UNSIGNED NOT NULL,
    dosen_id       INT UNSIGNED NOT NULL,
    nama_kelas     CHAR(2)      NOT NULL DEFAULT 'A',
    tahun_ajaran   VARCHAR(20)  NOT NULL,
    hari           ENUM('Senin','Selasa','Rabu','Kamis','Jumat','Sabtu') NOT NULL,
    jam_mulai      TIME         NOT NULL,
    jam_selesai    TIME         NOT NULL,
    ruang          VARCHAR(20)  NOT NULL,
    UNIQUE KEY uq_kelas (matakuliah_id, nama_kelas, tahun_ajaran),
    CONSTRAINT fk_kelas_mk    FOREIGN KEY (matakuliah_id) REFERENCES matakuliah(id),
    CONSTRAINT fk_kelas_dosen FOREIGN KEY (dosen_id)      REFERENCES dosen(id)
) ENGINE=InnoDB;

CREATE TABLE peserta_kelas (
    kelas_id      INT UNSIGNED NOT NULL,
    mahasiswa_id  INT UNSIGNED NOT NULL,
    PRIMARY KEY (kelas_id, mahasiswa_id),
    CONSTRAINT fk_peserta_kelas FOREIGN KEY (kelas_id)     REFERENCES kelas(id)     ON DELETE CASCADE,
    CONSTRAINT fk_peserta_mhs   FOREIGN KEY (mahasiswa_id) REFERENCES mahasiswa(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- Satu sesi tatap muka. Dosen membuka sesi -> muncul kode presensi yang berlaku sampai berakhir_at.
CREATE TABLE pertemuan (
    id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    kelas_id      INT UNSIGNED NOT NULL,
    pertemuan_ke  TINYINT UNSIGNED NOT NULL,
    tanggal       DATE         NOT NULL,
    topik         VARCHAR(150) NOT NULL,
    kode          CHAR(6)      NOT NULL,
    status        ENUM('dibuka','ditutup') NOT NULL DEFAULT 'dibuka',
    dibuka_at     DATETIME     NOT NULL,
    berakhir_at   DATETIME     NOT NULL,
    UNIQUE KEY uq_pertemuan (kelas_id, pertemuan_ke),
    CONSTRAINT fk_pertemuan_kelas FOREIGN KEY (kelas_id) REFERENCES kelas(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- H = hadir, I = izin, S = sakit, A = alpa (otomatis saat sesi ditutup)
CREATE TABLE presensi (
    id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    pertemuan_id  INT UNSIGNED NOT NULL,
    mahasiswa_id  INT UNSIGNED NOT NULL,
    status        ENUM('H','I','S','A') NOT NULL,
    waktu         DATETIME     NULL,
    keterangan    VARCHAR(150) NULL,
    UNIQUE KEY uq_presensi (pertemuan_id, mahasiswa_id),
    CONSTRAINT fk_presensi_pertemuan FOREIGN KEY (pertemuan_id) REFERENCES pertemuan(id) ON DELETE CASCADE,
    CONSTRAINT fk_presensi_mhs       FOREIGN KEY (mahasiswa_id) REFERENCES mahasiswa(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE pengumuman (
    id          INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    judul       VARCHAR(150) NOT NULL,
    isi         TEXT         NOT NULL,
    untuk       ENUM('semua','dosen','mahasiswa') NOT NULL DEFAULT 'semua',
    user_id     INT UNSIGNED NOT NULL,
    created_at  DATETIME     NOT NULL,
    CONSTRAINT fk_pengumuman_user FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB;

-- View rekap kehadiran per mahasiswa per kelas.
-- Dihitung dari pertemuan yang sudah ditutup dan tercatat untuk mahasiswa tersebut
-- (saat sesi ditutup semua peserta pasti tercatat, minimal sebagai Alpa), sehingga
-- mahasiswa yang baru ditambahkan ke kelas tidak dihitung absen untuk pertemuan sebelumnya.
CREATE VIEW v_rekap_kehadiran AS
SELECT pk.kelas_id, pk.mahasiswa_id,
       COUNT(pr.id)                       AS total_pertemuan,
       COALESCE(SUM(pr.status = 'H'), 0)  AS hadir,
       COALESCE(SUM(pr.status = 'I'), 0)  AS izin,
       COALESCE(SUM(pr.status = 'S'), 0)  AS sakit,
       COALESCE(SUM(pr.status = 'A'), 0)  AS alpa,
       ROUND(COALESCE(SUM(pr.status = 'H'), 0) / NULLIF(COUNT(pr.id), 0) * 100, 1) AS persen
FROM peserta_kelas pk
LEFT JOIN pertemuan p ON p.kelas_id = pk.kelas_id AND p.status = 'ditutup'
LEFT JOIN presensi pr ON pr.pertemuan_id = p.id AND pr.mahasiswa_id = pk.mahasiswa_id
GROUP BY pk.kelas_id, pk.mahasiswa_id;

